    public static final class Template {
        public final String id;
        public final String occasionId;
        public final String headline;
        public final String body;
        public final String details;
        public final int styleIndex;
        public final int paletteIndex;
        public final int textColor;

        Template(String id, String occasionId, String headline, String body, String details,
                 int styleIndex, int paletteIndex, int textColor) {
            this.id = id;
            this.occasionId = occasionId;
            this.headline = headline;
            this.body = body;
            this.details = details;
            this.styleIndex = styleIndex;
            this.paletteIndex = paletteIndex;
            this.textColor = textColor;
        }
    }

    public static final class Occasion {
        public final String id;
        public final String title;
        public final String emoji;
        public final List<Template> templates = new ArrayList<Template>();

        Occasion(String id, String title, String emoji) {
            this.id = id;
            this.title = title;
            this.emoji = emoji;
        }
    }

    public static final List<Occasion> OCCASIONS = new ArrayList<Occasion>();

    /**
     * بتضيف مناسبة بقوالبها. النمط والألوان بيتوزعوا تلقائيًا: كل ١٠ قوالب بيستخدموا
     * الأنماط العشرة، واللوحات من القائمة الخاصة بالمناسبة.
     */
    private static void occ(String id, String title, String emoji, int[] palettes,
                            String details, String[][] items) {
        Occasion o = new Occasion(id, title, emoji);
        int occIndex = OCCASIONS.size();
        for (int i = 0; i < items.length; i++) {
            int style = (i * 3 + occIndex) % STYLES.length;
            int palette = palettes[i % palettes.length];
            o.templates.add(new Template(id + "_" + (i + 1), id, items[i][0], items[i][1], details,
                    style, palette, PALETTES[palette].defaultTextColor));
        }
        OCCASIONS.add(o);
    }

